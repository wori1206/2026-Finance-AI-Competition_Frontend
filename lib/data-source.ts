"use client";

/**
 * 「지금 화면에 보이는 지출계획이 «어디서 왔는가»」를 한 곳에 적어 둡니다.
 *
 * ══════════════════════════════════════════════════════════════════════
 * 🔴 왜 필요한가 — 조용한 폴백이 «사실을 숨기고» 있었습니다.
 *
 *    `plan-service.ts` 는 서버 호출이 실패하면 `catch` 에서 예시 데이터로
 *    되돌아갑니다. 화면이 텅 비는 것보다 낫다는 판단이었고 그 판단은 맞습니다.
 *    문제는 «말을 안 한다» 는 것입니다 — 콘솔에 warn 한 줄만 남습니다.
 *
 *    2026-09-05 실측. 배포본(Vercel)에서:
 *      · `NEXT_PUBLIC_API_BASE` 는 들어가 있음 (Cloud Run 주소)
 *      · `NEXT_PUBLIC_SUPABASE_*` 는 «비어 있음» → 인증켜짐=false → 토큰 없음
 *      · 토큰 없이 `GET /api/plans` → 200 · 건수 0 (게스트는 org_id IS NULL 행만)
 *    그래서 화면에는 예시 3건 + 예전에 브라우저에 저장된 「123」 같은 시험 입력이
 *    떠 있었고, 그게 DB 값인지 예시인지 «화면만 봐서는 알 길이 없었습니다».
 *    오너가 직접 「이거 너가 띄운 거야?」 하고 물어야 했습니다. 그건 화면의 잘못입니다.
 *
 * 🔴 이 파일은 «상태를 만들지 않습니다». 마지막 목록 조회가 어떻게 끝났는지
 *    기록만 하고, 화면이 그걸 읽어 배너 한 줄을 그립니다. 서버 연동이 정상이면
 *    아무것도 안 그립니다 — 잘 되는 날 배너가 뜨면 그게 더 나쁩니다.
 * ══════════════════════════════════════════════════════════════════════
 */

export type 출처 =
  /** 서버에서 받았습니다. 배너 없음. */
  | "서버"
  /** `NEXT_PUBLIC_API_BASE` 가 비어 있어 서버를 아예 안 부릅니다. */
  | "예시_주소없음"
  /** 서버를 불렀는데 못 닿았습니다 (네트워크·CORS·서버 다운). */
  | "예시_연결실패"
  /** 서버가 403 — 로그인은 됐는데 명부(tenant.accounts)에 없는 계정입니다. */
  | "예시_미등록계정"
  /** 서버가 401 — 토큰이 만료됐거나 유효하지 않습니다. */
  | "예시_로그인만료";

export type 출처기록 = {
  값: 출처;
  /** 서버가 준 사유 원문. 개발자용이고 화면에는 안 씁니다. */
  사유?: string;
};

let 마지막: 출처기록 = { 값: "서버" };

/** 구독자 — React 가 다시 그리게 합니다. */
const 듣는이 = new Set<() => void>();

export function 출처기록하기(값: 출처, 사유?: string): void {
  // 🔴 같은 값이면 알리지 않습니다. 목록을 다시 부를 때마다 화면 전체가
  //    다시 그려지는 것을 막습니다.
  if (마지막.값 === 값 && 마지막.사유 === 사유) return;
  마지막 = { 값, 사유 };
  for (const f of 듣는이) f();
}

export function 지금출처(): 출처기록 {
  return 마지막;
}

export function 출처구독(f: () => void): () => void {
  듣는이.add(f);
  return () => {
    듣는이.delete(f);
  };
}

/**
 * 배너 문구. `null` 이면 «아무것도 그리지 않습니다».
 *
 * 🔴 사용자가 할 수 있는 행동을 «같이» 말합니다. 「예시 데이터입니다」만 쓰면
 *    사용자는 고장으로 읽고 아무것도 못 합니다.
 */
export function 출처문구(
  r: 출처기록 = 마지막,
): { 제목: string; 설명: string; 심각도: "안내" | "주의" } | null {
  switch (r.값) {
    case "서버":
      return null;
    case "예시_주소없음":
      return {
        제목: "예시 데이터를 보고 있습니다.",
        설명:
          "서버 주소가 설정되지 않아 실제 자료 대신 예시를 보여주고 있습니다. 저장한 내용은 이 브라우저에만 남습니다.",
        심각도: "안내",
      };
    case "예시_연결실패":
      return {
        제목: "서버에 연결하지 못해 예시 데이터를 보여주고 있습니다.",
        설명:
          "잠시 뒤 새로고침해 주세요. 계속 같으면 서버가 내려가 있거나 접근이 막힌 상태입니다.",
        심각도: "주의",
      };
    case "예시_미등록계정":
      return {
        제목: "이 계정은 아직 기관에 등록되지 않았습니다.",
        설명:
          "로그인은 되었지만 서버에 소속 기관이 없어 실제 자료를 불러오지 못했습니다. 지금 보이는 것은 예시입니다. 관리자에게 계정 등록을 요청해 주세요.",
        심각도: "주의",
      };
    case "예시_로그인만료":
      return {
        제목: "로그인이 만료되어 예시 데이터를 보여주고 있습니다.",
        설명: "다시 로그인하면 실제 자료가 표시됩니다.",
        심각도: "주의",
      };
  }
}
