/**
 * 🔴 **사용자가 마이페이지에서 «직접 고친» 값만** 이 브라우저에 기억합니다.
 *
 *    홈·사이드바·마이페이지가 각자 값을 들고 있어서, 마이페이지에서 고쳐도 홈은
 *    옛 값이 그대로 남았습니다. 목 서버는 저장을 안 받고 실서버의 `PUT /api/profile`
 *    도 아직 스텁이라, 서버만 믿으면 고친 값이 새로고침에 사라집니다.
 *
 * 🔴 **서버가 준 값은 여기 안 넣습니다** (2026-09-06). 전에는 `협약읽기()` 결과를
 *    그대로 기억했는데, 서버의 2024 날짜가 브라우저에 눌어붙어서 코드를 고쳐도
 *    화면이 안 바뀌었습니다. 이제 저장 버튼을 누른 값만 들어옵니다.
 *
 * 🔴 그래서 열쇠 이름에 `-v2` 를 붙입니다 — 이미 2024 가 눌어붙은 브라우저가
 *    옛 열쇠를 계속 읽으면 안 됩니다. 이름을 바꾸면 그 값은 조용히 무시됩니다.
 */
const 협약KEY = "checkumait-협약정보-v2";

export function 협약기억(c: 협약정보): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(협약KEY, JSON.stringify(c));
  } catch {
    /* 무시 */
  }
}

export function 기억된협약(): 협약정보 | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = localStorage.getItem(협약KEY);
    if (!raw) return null;
    const v = JSON.parse(raw) as 협약정보;
    if (!v || typeof v !== "object") return null;
    return {
      시작일: 글자(v.시작일),
      종료일: 글자(v.종료일),
      정부지원: 숫자(v.정부지원),
      자기부담: 숫자(v.자기부담),
    };
  } catch {
    return null;
  }
}

/**
 * 종료일까지 남은 날. 없으면 `null`.
 * 🔴 「D-129」가 화면에 박혀 있어서 날짜가 지나도 그대로였습니다.
 */
export function 남은날(종료일: string): number | null {
  if (!종료일) return null;
  const 끝 = new Date(`${종료일}T00:00:00`).getTime();
  if (Number.isNaN(끝)) return null;
  const 오늘 = new Date();
  const 기준 = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate()).getTime();
  return Math.ceil((끝 - 기준) / 86400000);
}

/**
 * 화면에 쓰는 D-day 표기. 협약이 없으면 `null`(아무것도 안 그림).
 * 🔴 지난 협약에 「D--554」가 찍히던 자리입니다 — 음수는 「종료」로 말합니다.
 */
export function 디데이표기(종료일: string): string | null {
  const 남음 = 남은날(종료일);
  if (남음 == null) return null;
  if (남음 > 0) return `D-${남음}`;
  return 남음 === 0 ? "D-DAY" : "종료";
}

/** "2026-03-01" ~ "2026-12-31" → "2026.03.01 ~ 2026.12.31" */
export function 기간표기(시작일: string, 종료일: string): string {
  if (!시작일 && !종료일) return "—";
  return `${날짜표기(시작일)} ~ ${날짜표기(종료일)}`;
}

/**
 * 화면이 «첫 그림» 에 그려야 할 협약 정보 — 동기 함수입니다.
 *
 * 순서: **사용자가 고친 값 → 고른 사업의 시연값**.
 *
 * 🔴 `useState` 의 초기값으로 그대로 넘길 수 있게 «동기» 로 남겨 둡니다 —
 *    첫 그림부터 맞는 값이 나오므로 숫자가 한 번 바뀌는 깜빡임이 없습니다.
 *    서버 렌더에서는 `선택사업()`·`기억된협약()` 이 둘 다 기본값으로 내려가
 *    `시연협약` 이 나옵니다(그 시점 화면은 로그인 화면이라 이 값을 안 그립니다).
 *
 * 🔴 서버 값은 여기서 안 읽습니다 — `GET /api/profile` 은 네트워크 호출이라
 *    동기로 못 답합니다. 서버 값이 필요하면 `서버협약읽기()` 를 따로 불러
 *    받은 뒤 이 값 위에 덮으세요(`use협약()` 이 하는 방식).
 */
export function 지금협약(): 협약정보 {
  const 기억 = 기억된협약();
  return 기억 && 값있음(기억) ? 기억 : 사업협약(선택사업());
}

/**
 * `GET /api/profile` 을 읽어 협약정보로 옮깁니다. 실패하거나 서버가
 * 「의미 있는 값」을 안 주면 `null` — 그러면 호출부는 시연값을 그대로 씁니다.
 *
 * 🔴 2026-09-06 에는 이 함수가 없었습니다 — 그날 운영 `tenant.f_profile` 의
 *    협약기간이 2024-03-01~2025-02-28(이미 만료)로 박혀 있어서, 읽으면 D-day
 *    자리가 「종료」로 돌아갔습니다. 원인은 «화면 설계» 가 아니라 «데이터»
 *    였는데, 그때는 화면이 서버 읽기를 통째로 껐습니다. 담당자가 해당 행을
 *    2026-03-01~2026-12-31 로 고쳤으므로(2026-09-07) 다시 읽습니다.
 *
 * 🔴 **사용자가 마이페이지에서 직접 고친 값이 있으면 이 함수를 부르지 않는
 *    것은 호출부 책임입니다** — 로컬에 남긴 사용자 결정이 서버 값보다 셉니다
 *    (`use협약()` 참고). 이 함수 자체는 그 판단을 하지 않고 서버 값만 옮깁니다.
 */
export async function 서버협약읽기(): Promise<협약정보 | null> {
  if (!API켜짐()) return null;
  try {
    const r = await 프로필읽기();
    const f1 = (r?.["f1"] ?? {}) as Record<string, unknown>;
    const c: 협약정보 = {
      시작일: 글자(f1["협약시작일"]),
      종료일: 글자(f1["협약종료일"]),
      정부지원: 숫자(f1["정부지원_현금"]),
      자기부담: 숫자(f1["자기부담_현금"]),
    };
    return 값있음(c) ? c : null;
  } catch {
    return null;
  }
}

export type 저장결과 = "저장됨" | "서버가안받음" | "실패";

export async function 협약쓰기(c: 협약정보): Promise<저장결과> {
  if (!API켜짐()) return "서버가안받음";
  try {
    const r = (await 프로필저장({
      f1: {
        정부지원_현금: c.정부지원,
        자기부담_현금: c.자기부담,
        협약시작일: c.시작일 || null,
        협약종료일: c.종료일 || null,
      },
    })) as Record<string, unknown>;
    return r?.["저장"] === false ? "서버가안받음" : "저장됨";
  } catch {
    return "실패";
  }
}

/* ── 화면 표기 ─────────────────────────────── */

export function 원(n: number): string {
  return `${(n || 0).toLocaleString("ko-KR")}원`;
}

/** "2026-03-01" → "2026.03.01" · 없으면 "—" */
export function 날짜표기(s: string): string {
  return s ? s.replace(/-/g, ".") : "—";
}
