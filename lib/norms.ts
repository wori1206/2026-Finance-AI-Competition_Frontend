/** "2026 초격차 스타트업 1000+" → "초격차스타트업1000" */
function 벗김(s: string): string {
  return (s ?? "")
    .replace(/^\s*20\d\d\s*/, "")
    .replace(/[\s·・+()]/g, "")
    .toLowerCase();
}

/**
 * 이 사업에 적용되는 규범 목록. 화면 위에서부터 그대로 그립니다.
 *
 * 🔴 표에 없는 사업이면 지어내지 않고 «사업명 + 세부관리기준» 까지만 말합니다.
 *    창업진흥원 사업의 L2 규범 이름이 전부 그 꼴이라 틀리지 않습니다.
 */
export function 적용규범(사업: string): 적용규범항목[] {
  const 키 = 벗김(사업);
  const 찾음 = 표.find((r) => r.열쇠.some((k) => 키.includes(벗김(k))));
  const 세부: 적용규범항목 = {
    제목: 찾음 ? 찾음.세부기준 : `${(사업 ?? "").replace(/^\s*20\d\d\s*/, "").trim()} 세부관리기준`,
    설명: "중소벤처기업부·창업진흥원 · 이 사업의 집행 기준",
  };
  return [세부, ...(찾음?.상위 ?? [통합관리지침])];
}
